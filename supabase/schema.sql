-- VTS Energy & Security V2 Supabase schema
create extension if not exists pgcrypto;

-- Admin users table
create table if not exists public.admin_users(
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz default now()
);

-- Site settings table
create table if not exists public.site_settings(
  id bigint primary key default 1 check(id=1),
  company_name text not null,
  legal_name text not null,
  registration_number text not null,
  phone text not null,
  phone2 text,
  whatsapp text,
  sales_email text not null,
  info_email text not null,
  address text not null,
  coverage text,
  mission text,
  vision text,
  values text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Categories table
create table if not exists public.categories(
  id bigint generated by default as identity primary key,
  name text unique not null,
  active boolean default true,
  display_order int default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Products table
create table if not exists public.products(
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text unique not null,
  category_id bigint references public.categories(id) on delete set null,
  category text,
  short_description text,
  description text not null,
  price numeric,
  price_type text default 'per unit',
  promotion_status text default 'none',
  promotion_type text default 'on_sale',
  original_price numeric,
  sale_price numeric,
  image_url text,
  features jsonb,
  specifications jsonb,
  active boolean default true,
  featured boolean default false,
  display_order int default 0,
  is_demo boolean default false,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.products add column if not exists specifications jsonb;
alter table public.products add column if not exists promotion_status text default 'none';
alter table public.products add column if not exists promotion_type text default 'on_sale';
alter table public.products add column if not exists original_price numeric;
alter table public.products add column if not exists sale_price numeric;

-- Services table
create table if not exists public.services(
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null check(category in('Energy Solutions','Digital Security Solutions')),
  description text not null,
  display_order int default 0,
  image text,
  active boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Admin function
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.admin_users where user_id=auth.uid());
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon,authenticated;

